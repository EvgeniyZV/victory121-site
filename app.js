  /* ==========================================================================
     4. Hero Equipment Carousel (Auto-Play + Interactive Dots)
     ========================================================================== */
  let carouselInterval = null;

  function setCarouselSlide(index) {
    if (!heroSlides.length) return;
    state.carouselIndex = (index + heroSlides.length) % heroSlides.length;

    heroSlides.forEach((slide, i) => {
      slide.classList.toggle('is-active', i === state.carouselIndex);
    });

    heroDots.forEach((dot, i) => {
      const active = i === state.carouselIndex;
      dot.classList.toggle('is-active', active);
      dot.setAttribute('aria-selected', active ? 'true' : 'false');
    });
  }

  function startCarousel() {
    stopCarousel();
    carouselInterval = window.setInterval(() => {
      setCarouselSlide(state.carouselIndex + 1);
    }, 4500);
  }

  function stopCarousel() {
    if (carouselInterval) {
      window.clearInterval(carouselInterval);
      carouselInterval = null;
    }
  }

  if (heroDots.length) {
    heroDots.forEach((dot) => {
      dot.addEventListener('click', () => {
        const targetIndex = Number(dot.getAttribute('data-carousel-goto') || 0);
        setCarouselSlide(targetIndex);
        startCarousel();
      });
    });
  }

  if (heroCarousel) {
    heroCarousel.addEventListener('mouseenter', stopCarousel);
    heroCarousel.addEventListener('mouseleave', startCarousel);
    startCarousel();
  }

  /* ==========================================================================
     5. Helper Functions & Input Sanitization
     ========================================================================== */
  function sanitizeUserText(raw, maxLen = 200) {
    if (typeof raw !== 'string') return '';
    return raw
      .replace(/[\u0000-\u001F\u007F<>]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .slice(0, maxLen);
  }

  function showToast(message) {
    if (!toastRegion) return;
    toastRegion.replaceChildren();
    const el = document.createElement('div');
    el.className = 'toast-msg';
    el.textContent = message;
    toastRegion.appendChild(el);
    window.clearTimeout(showToast._timer);
    showToast._timer = window.setTimeout(() => {
      if (toastRegion.contains(el)) {
        toastRegion.removeChild(el);
      }
    }, 3200);
  }

  function renderSymptomChips() {
    if (!symptomChipContainer) return;
    const service = SERVICE_DETAILS[state.selectedDevice] || SERVICE_DETAILS.printers;
    const symptoms = service.symptoms[state.lang] || service.symptoms.ru;
    const dict = I18N[state.lang];

    if (state.selectedSymptom !== OTHER_SYMPTOM_KEY && !symptoms.includes(state.selectedSymptom)) {
      state.selectedSymptom = symptoms[0] || '';
    }

    symptomChipContainer.replaceChildren();
    symptoms.forEach((symptomText) => {
      const btn = document.createElement('button');
      btn.type = 'button';
      const isSelected = symptomText === state.selectedSymptom;
      btn.className = 'chip chip--sm' + (isSelected ? ' is-selected' : '');
      btn.setAttribute('aria-pressed', isSelected ? 'true' : 'false');
      btn.textContent = symptomText;
      btn.addEventListener('click', () => {
        state.selectedSymptom = symptomText;
        renderSymptomChips();
      });
      symptomChipContainer.appendChild(btn);
    });

    // Add the "✎ Другое (описать свою ошибку)" button
    const otherBtn = document.createElement('button');
    otherBtn.type = 'button';
    const isOtherSelected = state.selectedSymptom === OTHER_SYMPTOM_KEY;
    otherBtn.className = 'chip chip--sm chip--other' + (isOtherSelected ? ' is-selected' : '');
    otherBtn.setAttribute('aria-pressed', isOtherSelected ? 'true' : 'false');
    otherBtn.textContent = dict.symptom_other_btn;
    otherBtn.addEventListener('click', () => {
      state.selectedSymptom = OTHER_SYMPTOM_KEY;
      renderSymptomChips();
      if (customSymptomInput) {
        customSymptomInput.focus();
      }
    });
    symptomChipContainer.appendChild(otherBtn);

    if (customSymptomBox) {
      customSymptomBox.hidden = !isOtherSelected;
    }
  }

  function syncDeviceChipsUI() {
    if (!deviceChipContainer) return;
    const buttons = deviceChipContainer.querySelectorAll('[data-device]');
    buttons.forEach((btn) => {
      const active = btn.getAttribute('data-device') === state.selectedDevice;
      btn.classList.toggle('is-selected', active);
      btn.setAttribute('aria-pressed', active ? 'true' : 'false');
    });
  }

  function syncBrandUI() {
    if (brandChipContainer) {
      const buttons = brandChipContainer.querySelectorAll('[data-brand]');
      buttons.forEach((btn) => {
        const active = btn.getAttribute('data-brand') === state.selectedBrand;
        btn.classList.toggle('is-selected', active);
        btn.setAttribute('aria-pressed', active ? 'true' : 'false');
      });
    }

    document.querySelectorAll('[data-brand-card]').forEach((card) => {
      const active = card.getAttribute('data-brand-card') === state.selectedBrand;
      card.classList.toggle('is-highlighted', active);
    });
  }

  function applyLanguage(lang) {
    state.lang = I18N[lang] ? lang : 'ru';
    document.documentElement.lang = state.lang === 'kz' ? 'kk' : 'ru';
    const dict = I18N[state.lang];

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
      const isCurrent = btn.getAttribute('data-lang-btn') === state.lang;
      btn.classList.toggle('is-active', isCurrent);
      btn.setAttribute('aria-pressed', isCurrent ? 'true' : 'false');
    });

    renderSymptomChips();

    if (serviceModal && serviceModal.open) {
      populateServiceModal(state.activeModalService);
    }
  }

  function populateServiceModal(serviceId) {
    const data = SERVICE_DETAILS[serviceId];
    if (!data) return;
    state.activeModalService = serviceId;

    const lang = state.lang;
    const codeEl = document.getElementById('modal-service-code');
    const titleEl = document.getElementById('modal-service-title');
    const descEl = document.getElementById('modal-service-desc');
    const symptomsList = document.getElementById('modal-service-symptoms');
    const worksList = document.getElementById('modal-service-works');
    const metaEl = document.getElementById('modal-service-meta');
    const waDirectLink = document.getElementById('modal-wa-direct-link');

    if (codeEl) codeEl.textContent = data.code;
    if (titleEl) titleEl.textContent = data.title[lang] || data.title.ru;
    if (descEl) descEl.textContent = data.desc[lang] || data.desc.ru;
    if (metaEl) metaEl.textContent = data.meta[lang] || data.meta.ru;

    if (symptomsList) {
      symptomsList.replaceChildren();
      (data.symptoms[lang] || data.symptoms.ru).forEach((item) => {
        const li = document.createElement('li');
        li.textContent = item;
        symptomsList.appendChild(li);
      });
    }

    if (worksList) {
      worksList.replaceChildren();
      (data.works[lang] || data.works.ru).forEach((item) => {
        const li = document.createElement('li');
        li.textContent = item;
        worksList.appendChild(li);
      });
    }

    if (waDirectLink) {
      const msg = lang === 'kz'
        ? `Сәлеметсіз бе! Victory 121 сервис орталығына «${data.title.kz}» бойынша сұрағым бар.`
        : `Здравствуйте! Интересует «${data.title.ru}» в сервисном центре Victory 121.`;
      waDirectLink.href = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(msg)}`;
    }
  }

